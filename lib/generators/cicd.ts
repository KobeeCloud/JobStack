// ─────────────────────────────────────────────
// Prometheus scrape config
// ─────────────────────────────────────────────
function generatePrometheus(label: string, cfg: Record<string, any>): CICDOutput {
  const content = `# Generated by JobStack — ${label}
global:
  scrape_interval: ${cfg.scrapeInterval || '15s'}
  evaluation_interval: ${cfg.evaluationInterval || '15s'}

alerting:
  alertmanagers:
    - static_configs:
        - targets: []
          # - alertmanager:9093

rule_files: []
  # - "alert_rules.yml"

scrape_configs:
  - job_name: 'prometheus'
    static_configs:
      - targets: ['localhost:${cfg.port || 9090}']

  - job_name: 'application'
    metrics_path: '/metrics'
    static_configs:
      - targets: ['app:8080']
    relabel_configs:
      - source_labels: [__address__]
        target_label: instance

  - job_name: 'node-exporter'
    static_configs:
      - targets: ['node-exporter:9100']

  # Add more scrape targets as needed
`
  return {
    filename: 'prometheus.yml',
    content,
    language: 'yaml',
    generatorType: 'monitoring',
    componentLabel: label,
  }
}

