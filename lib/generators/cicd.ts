/**
 * CI/CD Config Generator
 *
 * Converts CI/CD, Kubernetes, and monitoring nodes on the diagram canvas
 * into their respective configuration file formats:
 *
 *   github-actions  → .github/workflows/deploy.yml
 *   gitlab-ci       → .gitlab-ci.yml
 *   jenkins         → Jenkinsfile
 *   argocd          → argocd-app.yaml
 *   helm            → helm/values.yaml
 *   prometheus      → prometheus.yml
 *   datadog         → datadog.yaml
 *   rabbitmq/kafka  → docker-compose service entry
 *
 * Components that are 'documentation' or 'annotation' generate nothing —
 * the function returns null for them and the caller should inform the user.
 */

import { Node, Edge } from '@xyflow/react'
import { getComponentById, getEffectiveGeneratorType } from '@/lib/catalog'

export interface CICDOutput {
  filename: string
  content: string
  language: 'yaml' | 'groovy' | 'json' | 'bash'
  generatorType: string
  componentLabel: string
}

export interface CICDResult {
  outputs: CICDOutput[]
  skipped: { label: string; reason: string }[]
}

interface NodeData {
  label?: string
  componentId?: string
  component?: string
  config?: Record<string, any>
  [key: string]: unknown
}

// ─────────────────────────────────────────────
// GitHub Actions
// ─────────────────────────────────────────────
function generateGitHubActions(label: string, cfg: Record<string, any>): CICDOutput {
  const branches = (cfg.branches as string[] | undefined) || ['main']
  const triggers = (cfg.triggers as string[] | undefined) || ['push', 'pull_request']
  const runsOn = cfg.runsOn || 'ubuntu-latest'
  const nodeVersion = cfg.nodeVersion || '20'
  const deployTarget = cfg.deployTarget || 'kubernetes'

  const onSection = triggers.map((t: string) => {
    if (t === 'push') return `  push:\n    branches: [${branches.map((b: string) => `"${b}"`).join(', ')}]`
    if (t === 'pull_request') return `  pull_request:\n    branches: [${branches.map((b: string) => `"${b}"`).join(', ')}]`
    if (t === 'schedule') return `  schedule:\n    - cron: '0 2 * * *'`
    return `  ${t}: {}`
  }).join('\n')

  const deployStep = deployTarget === 'kubernetes'
    ? `      - name: Deploy to Kubernetes\n        run: kubectl apply -f k8s/`
    : deployTarget === 'ecs'
    ? `      - name: Deploy to ECS\n        run: aws ecs update-service --cluster production --service \${{ github.event.repository.name }} --force-new-deployment`
    : deployTarget === 'appservice'
    ? `      - name: Deploy to Azure App Service\n        uses: azure/webapps-deploy@v2\n        with:\n          app-name: \${{ vars.AZURE_APP_NAME }}`
    : deployTarget === 'lambda'
    ? `      - name: Deploy to Lambda\n        run: aws lambda update-function-code --function-name \${{ vars.LAMBDA_FUNCTION_NAME }} --zip-file fileb://function.zip`
    : `      - name: Deploy\n        run: echo "Configure deploy step"`

  const content = `# Generated by JobStack — ${label}
# Modify triggers, jobs, and steps to match your project requirements.
name: CI/CD Pipeline

on:
${onSection}

env:
  NODE_VERSION: '${nodeVersion}'

jobs:
  build:
    name: Build & Test
    runs-on: ${runsOn}
    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: \${{ env.NODE_VERSION }}
          cache: 'npm'

      - name: Install dependencies
        run: npm ci

      - name: Run linter
        run: npm run lint --if-present

      - name: Run tests
        run: npm test --if-present

      - name: Build
        run: npm run build --if-present

  docker:
    name: Build & Push Docker Image
    runs-on: ${runsOn}
    needs: build
    if: github.ref == 'refs/heads/${branches[0]}'
    steps:
      - uses: actions/checkout@v4

      - name: Log in to container registry
        uses: docker/login-action@v3
        with:
          registry: \${{ vars.DOCKER_REGISTRY }}
          username: \${{ secrets.REGISTRY_USERNAME }}
          password: \${{ secrets.REGISTRY_PASSWORD }}

      - name: Build & push
        uses: docker/build-push-action@v5
        with:
          push: true
          tags: \${{ vars.DOCKER_REGISTRY }}/\${{ github.event.repository.name }}:\${{ github.sha }}

  deploy:
    name: Deploy
    runs-on: ${runsOn}
    needs: docker
    if: github.ref == 'refs/heads/${branches[0]}'
    environment: production
    steps:
${deployStep}
`
  return {
    filename: '.github/workflows/deploy.yml',
    content,
    language: 'yaml',
    generatorType: 'cicd',
    componentLabel: label,
  }
}

// ─────────────────────────────────────────────
// GitLab CI/CD
// ─────────────────────────────────────────────
function generateGitLabCI(label: string, cfg: Record<string, any>): CICDOutput {
  const stages = (cfg.stages as string[] | undefined) || ['build', 'test', 'deploy']
  const branches = (cfg.branches as string[] | undefined) || ['main']

  const content = `# Generated by JobStack — ${label}
stages:${stages.map((s: string) => `\n  - ${s}`).join('')}

variables:
  DOCKER_DRIVER: overlay2
  DOCKER_TLS_CERTDIR: "/certs"

.default_rules: &default_rules
  rules:
    - if: '$CI_COMMIT_BRANCH == "${branches[0]}"'
    - if: '$CI_PIPELINE_SOURCE == "merge_request_event"'

build:
  stage: build
  image: node:20-alpine
  cache:
    paths:
      - node_modules/
  script:
    - npm ci
    - npm run build
  artifacts:
    paths:
      - dist/
    expire_in: 1 hour
  <<: *default_rules

test:
  stage: test
  image: node:20-alpine
  needs: [build]
  script:
    - npm ci
    - npm run lint --if-present
    - npm test --if-present
  coverage: '/Lines\\s*:\\s*(\\d+\\.?\\d*)%/'
  <<: *default_rules

docker_build:
  stage: build
  image: docker:24
  services:
    - docker:24-dind
  needs: [test]
  script:
    - docker login -u \$CI_REGISTRY_USER -p \$CI_REGISTRY_PASSWORD \$CI_REGISTRY
    - docker build -t \$CI_REGISTRY_IMAGE:\$CI_COMMIT_SHA .
    - docker push \$CI_REGISTRY_IMAGE:\$CI_COMMIT_SHA
  only:
    - ${branches[0]}

deploy:
  stage: deploy
  image: bitnami/kubectl:latest
  needs: [docker_build]
  script:
    - kubectl apply -f k8s/
    - kubectl rollout status deployment/\$CI_PROJECT_NAME
  environment:
    name: production
  only:
    - ${branches[0]}
`
  return {
    filename: '.gitlab-ci.yml',
    content,
    language: 'yaml',
    generatorType: 'cicd',
    componentLabel: label,
  }
}

// ─────────────────────────────────────────────
// Jenkinsfile (Declarative Pipeline)
// ─────────────────────────────────────────────
function generateJenkinsfile(label: string, cfg: Record<string, any>): CICDOutput {
  const stages = (cfg.stages as string[] | undefined) || ['Checkout', 'Build', 'Test', 'Docker Build', 'Deploy']
  const runsOn = cfg.runsOn || 'any'

  const stageBlocks = stages.map((s: string) => {
    if (s.toLowerCase() === 'checkout') {
      return `        stage('${s}') {\n            steps {\n                checkout scm\n            }\n        }`
    }
    if (s.toLowerCase() === 'build') {
      return `        stage('${s}') {\n            steps {\n                sh 'npm ci && npm run build'\n            }\n        }`
    }
    if (s.toLowerCase() === 'test') {
      return `        stage('${s}') {\n            steps {\n                sh 'npm test'\n            }\n            post {\n                always {\n                    junit 'test-results/**/*.xml'\n                }\n            }\n        }`
    }
    if (s.toLowerCase().includes('docker')) {
      return `        stage('${s}') {\n            steps {\n                script {\n                    docker.build("\${env.IMAGE_NAME}:\${env.BUILD_NUMBER}")\n                        .push()\n                }\n            }\n        }`
    }
    return `        stage('${s}') {\n            steps {\n                sh 'echo Running ${s}'\n            }\n        }`
  }).join('\n\n')

  const content = `// Generated by JobStack — ${label}
// Declarative Pipeline
pipeline {
    agent { label '${runsOn}' }

    environment {
        IMAGE_NAME = "\${env.JOB_NAME.toLowerCase()}"
        REGISTRY   = credentials('docker-registry-url')
    }

    options {
        buildDiscarder(logRotator(numToKeepStr: '10'))
        timeout(time: 30, unit: 'MINUTES')
        disableConcurrentBuilds()
    }

    triggers {
        pollSCM('H/5 * * * *')
    }

    stages {
${stageBlocks}
    }

    post {
        success {
            echo 'Pipeline succeeded!'
            // slackSend message: "Build \${env.BUILD_NUMBER} succeeded"
        }
        failure {
            echo 'Pipeline failed!'
            // slackSend message: "Build \${env.BUILD_NUMBER} failed"
        }
        always {
            cleanWs()
        }
    }
}
`
  return {
    filename: 'Jenkinsfile',
    content,
    language: 'groovy',
    generatorType: 'cicd',
    componentLabel: label,
  }
}

// ─────────────────────────────────────────────
// ArgoCD Application Manifest
// ─────────────────────────────────────────────
function generateArgoCDApp(label: string, cfg: Record<string, any>): CICDOutput {
  const appName = label.toLowerCase().replace(/[^a-z0-9-]/g, '-')
  const content = `# Generated by JobStack — ${label}
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: ${appName}
  namespace: ${cfg.appNamespace || 'argocd'}
  labels:
    managed-by: jobstack
spec:
  project: default
  source:
    repoURL: ${cfg.repoUrl || 'https://github.com/org/repo'}
    targetRevision: ${cfg.targetRevision || 'HEAD'}
    path: k8s/
    # Uncomment for Helm:
    # chart: ${appName}
    # helm:
    #   valueFiles:
    #     - values.yaml
    #     - values-production.yaml
  destination:
    server: https://kubernetes.default.svc
    namespace: ${cfg.destinationNamespace || 'default'}
  syncPolicy:
    ${cfg.syncPolicy === 'automated' ? `automated:\n      selfHeal: ${cfg.selfHeal ?? true}\n      prune: ${cfg.prune ?? true}` : 'syncOptions: []'}
    syncOptions:
      - CreateNamespace=true
      - PrunePropagationPolicy=foreground
`
  return {
    filename: 'argocd-app.yaml',
    content,
    language: 'yaml',
    generatorType: 'kubernetes',
    componentLabel: label,
  }
}

