// ─────────────────────────────────────────────
// docker-compose service snippet
// ─────────────────────────────────────────────
function generateDockerCompose(id: string, label: string, cfg: Record<string, any>): CICDOutput {
  let serviceBlock: string

  if (id === 'rabbitmq') {
    serviceBlock = `  rabbitmq:
    image: rabbitmq:3-management
    environment:
      RABBITMQ_DEFAULT_USER: ${cfg.defaultUser || 'admin'}
      RABBITMQ_DEFAULT_PASS: \${RABBITMQ_PASSWORD}
      RABBITMQ_DEFAULT_VHOST: ${cfg.vhost || '/'}
    ports:
      - "${cfg.amqpPort || 5672}:5672"
      - "${cfg.managementPort || 15672}:15672"
    volumes:
      - rabbitmq_data:/var/lib/rabbitmq
    healthcheck:
      test: ["CMD", "rabbitmq-diagnostics", "ping"]
      interval: 30s
      timeout: 10s
      retries: 5`
  } else if (id === 'kafka') {
    serviceBlock = `  zookeeper:
    image: confluentinc/cp-zookeeper:7.5.0
    environment:
      ZOOKEEPER_CLIENT_PORT: 2181

  kafka:
    image: confluentinc/cp-kafka:7.5.0
    depends_on: [zookeeper]
    ports:
      - "${cfg.port || 9092}:9092"
    environment:
      KAFKA_BROKER_ID: ${cfg.brokerId ?? 1}
      KAFKA_ZOOKEEPER_CONNECT: zookeeper:2181
      KAFKA_ADVERTISED_LISTENERS: PLAINTEXT://kafka:${cfg.port || 9092}
      KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR: ${cfg.replicationFactor ?? 1}
      KAFKA_LOG_RETENTION_HOURS: ${cfg.retentionHours ?? 168}
      KAFKA_AUTO_CREATE_TOPICS_ENABLE: "true"`
  } else if (id === 'nats') {
    serviceBlock = `  nats:
    image: nats:2.10-alpine
    ports:
      - "${cfg.port || 4222}:4222"
      - "${cfg.monitorPort || 8222}:8222"
    command: >
      --jetstream
      --store_dir=/data
    volumes:
      - nats_data:/data`
  } else {
    serviceBlock = `  ${label.toLowerCase().replace(/[^a-z0-9-]/g, '-')}:
    image: # TODO: specify image
    ports:
      - "8080:8080"
    environment:
      NODE_ENV: production`
  }

  const volumesBlock = id === 'rabbitmq'
    ? '\nvolumes:\n  rabbitmq_data:'
    : id === 'nats'
    ? '\nvolumes:\n  nats_data:'
    : ''

  const content = `# Generated by JobStack — ${label}
# Add this service to your existing docker-compose.yml
version: '3.9'

services:
${serviceBlock}
${volumesBlock}
`
  return {
    filename: `docker-compose.${id}.yml`,
    content,
    language: 'yaml',
    generatorType: 'docker',
    componentLabel: label,
  }
}

// ─────────────────────────────────────────────
// Main entry point
// ─────────────────────────────────────────────
export function generateCICDConfigs(nodes: Node<NodeData>[], _edges: Edge[]): CICDResult {
  const outputs: CICDOutput[] = []
  const skipped: { label: string; reason: string }[] = []

  nodes.forEach(node => {
    const componentId = node.data?.componentId || node.data?.component
    if (!componentId) return

    const component = getComponentById(componentId)
    if (!component) return

    const genType = getEffectiveGeneratorType(component)
    if (genType === 'terraform') return // handled by terraform generator

    const label = String(node.data?.label || component.name)
    const cfg: Record<string, any> = {
      ...(component.cicd?.defaultConfig || {}),
      ...(node.data?.config || {}),
    }

    switch (componentId) {
      case 'github-actions':
        outputs.push(generateGitHubActions(label, cfg))
        break
      case 'gitlab-ci':
        outputs.push(generateGitLabCI(label, cfg))
        break
      case 'jenkins':
        outputs.push(generateJenkinsfile(label, cfg))
        break
      case 'argocd':
        outputs.push(generateArgoCDApp(label, cfg))
        break
      case 'helm':
        outputs.push(generateHelmValues(label, cfg))
        break
      case 'prometheus':
        outputs.push(generatePrometheus(label, cfg))
        break
      case 'datadog':
        outputs.push(generateDatadog(label, cfg))
        break
      case 'rabbitmq':
      case 'kafka':
      case 'nats':
      case 'docker':
        outputs.push(generateDockerCompose(componentId, label, cfg))
        break
      case 'documentation':
      case 'vault':
      case 'ansible':
      case 'terraform':
        skipped.push({ label, reason: 'Annotation-only component — used for architectural documentation only, no code generated' })
        break
      default:
        if (genType === 'documentation') {
          skipped.push({ label, reason: 'No code generator for this component type — used as architectural annotation' })
        } else if (genType === 'monitoring') {
          skipped.push({ label, reason: `Monitoring config for "${component.name}" — open the Output tab in the config panel to preview` })
        } else {
          skipped.push({ label, reason: `Generator type "${genType}" not yet implemented for ${component.name}` })
        }
    }
  })

  return { outputs, skipped }
}

/** Get only the nodes that a CI/CD generator can handle */
export function getCICDNodes(nodes: Node<NodeData>[]): Node<NodeData>[] {
  return nodes.filter(node => {
    const id = node.data?.componentId || node.data?.component
    if (!id) return false
    const component = getComponentById(id)
    if (!component) return false
    const genType = getEffectiveGeneratorType(component)
    return genType !== 'terraform' && genType !== 'documentation'
  })
}
